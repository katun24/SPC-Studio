    // Whether a ROM's song is one of SMW's original songs, compiled exactly as AddmusicK compiles it.
    public static bool IsOriginal(RomSong song)
    {
        foreach (var fingerprint in Fingerprints)
        {
            if (fingerprint.ByteCount == song.Data.Length && fingerprint.Checksum == ChecksumOf(song, fingerprint.AddressOffsets))
            {
                return true;
            }
        }

        return false;
    }

    // The checksum of a song's bytes with the address at each offset given made relative to where the song is loaded.
    private static string ChecksumOf(RomSong song, int[] addressOffsets)
    {
        byte[] relocated = (byte[])song.Data.Clone();
        foreach (int offset in addressOffsets)
        {
            int address = BinaryPrimitives.ReadUInt16LittleEndian(relocated.AsSpan(offset));
            BinaryPrimitives.WriteUInt16LittleEndian(relocated.AsSpan(offset), (ushort)(address - song.AramBase));
        }

        return Convert.ToHexString(SHA256.HashData(relocated));
    }

    // One original song's fingerprint.
    private sealed record Fingerprint(int ByteCount, string Checksum, int[] AddressOffsets);
